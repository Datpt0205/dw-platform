# The object's default access joins in the view, under the tenant of `ctx`,
# so the computation still reads only the views (record-access/02 gate (h)).
_V_GRANTS = f"""
    CREATE OR REPLACE VIEW studio.v_principal_grants WITH (security_invoker = true) AS{_CTX}
        SELECT k.object_id, k.action, g.depth, g.anchor_workspace_id, a.expires_at,
               o.default_access{_V_GRANTS_BODY}
        JOIN studio.object_defs o ON o.tenant_id = ctx.tenant_id AND o.id = k.object_id
        WHERE k.action IN ('read', 'create', 'update', 'delete', 'assign')
"""
_V_GRANTS_BEFORE = f"""
    CREATE VIEW studio.v_principal_grants WITH (security_invoker = true) AS{_CTX}
        SELECT k.object_id, k.action, g.depth, g.anchor_workspace_id, a.expires_at{_V_GRANTS_BODY}
        WHERE k.action IN ('read', 'create', 'update', 'delete', 'assign')
"""

ACTIONS = ("read", "create", "update", "delete", "assign")
ARMS = ("own", "keys", "tenant")
REACH_COLUMNS = (*(f"{action}_{arm}" for action in ACTIONS for arm in ARMS), "create_own_keys")
_W1_DEPTHS = "('own', 'workspace', 'tenant')"
# Which default access opens an action's tenant arm to a holder at any W1 depth.
_DEFAULT_OPENS = {
    "read": "('public_read', 'public_read_write')",
    "update": "('public_read_write')",
}


def _arm(action: str, arm: str, *, default_access: bool) -> str:
    if arm == "own":
        value, where = "g.object_id", f"g.depth IN {_W1_DEPTHS}"
    elif arm == "keys":
        value, where = (
            "studio.access_key(g.object_id, g.anchor_workspace_id)",
            "g.depth = 'workspace'",
        )
    else:
        value, where = "g.object_id", "g.depth = 'tenant'"
        if default_access and action in _DEFAULT_OPENS:
            where = (
                f"(g.depth = 'tenant' OR (g.depth IN {_W1_DEPTHS}"
                f" AND g.default_access IN {_DEFAULT_OPENS[action]}))"
            )
    return (
        f"coalesce(array_agg(DISTINCT {value})"
        f" FILTER (WHERE g.action = '{action}' AND {where}), '{{}}')"
    )


def _compute(*, default_access: bool) -> str:
    columns = ",\n            ".join(
        [
            *(
                _arm(action, arm, default_access=default_access)
                for action in ACTIONS
                for arm in ARMS
            ),
            "coalesce(array_agg(DISTINCT studio.access_key(g.object_id, g.anchor_workspace_id))"
            " FILTER (WHERE g.action = 'create' AND g.depth = 'own'), '{}')",
        ]
    )
    returns = ", ".join(f"{c} uuid[]" for c in REACH_COLUMNS)
    return f"""
    CREATE OR REPLACE FUNCTION studio.compute_principal_scope()
    RETURNS TABLE (workspace_ids uuid[], valid_until timestamp with time zone, {returns})
    LANGUAGE sql STABLE
    SET search_path = pg_catalog
    AS $$
        SELECT
            (SELECT coalesce(array_agg(DISTINCT w.workspace_id), '{{}}')
             FROM studio.v_principal_workspaces w),
            min(g.expires_at) FILTER (WHERE g.depth IN {_W1_DEPTHS}),
            {columns}
        FROM studio.v_principal_grants g
    $$
"""


