"""The content-addressed release a process is serving, read once at start.

Generated by ``make release-manifest`` into ``contracts/release/manifest.ref``;
every run records it so a result can be traced back to the exact artifact set
that produced it. Absent only in un-released development trees.

Here rather than in one app: the API starts runs a person asked for, the worker
the runs of the work its lanes claim (wf-lite/02), and a run's row names its
release however it began.
"""

from __future__ import annotations

from pathlib import Path

UNRELEASED = "unreleased"


def read_release_manifest_ref(repo_root: Path) -> str:
    path = repo_root / "contracts" / "release" / "manifest.ref"
    if path.exists():
        return path.read_text(encoding="utf-8").strip()
    return UNRELEASED
